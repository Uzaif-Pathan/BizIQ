"""Turn findings into explainable, prioritised recommendations (no external LLM).

* A rule fires only when at least one finding of its types has severity above "info".
* Every recommendation lists the ``finding_ids`` it came from (schema: at least one), quotes
  their evidence, and says which rule produced it and why.
* Priority = the highest severity among its findings (high -> high, medium -> medium,
  low -> low). Output is sorted high -> low, then by rule order.
* ``expected_direction`` is the direction we aim for on a metric, not a forecast of results
  (null for data-quality actions such as completing the expense list).
* Business type picks the wording (retail / service; anything else -> generic).
* With ``evidence_level == "low"`` each recommendation gets a caveat that it rests on limited data.
"""

from __future__ import annotations

from collections import defaultdict
from typing import Any, Iterable

from .rules import RULES, Rule

SEVERITY_RANK = {"info": 0, "low": 1, "medium": 2, "high": 3}
PRIORITY_BY_RANK = {1: "low", 2: "medium", 3: "high"}
PRIORITY_ORDER = {"high": 0, "medium": 1, "low": 2}
MAX_EVIDENCE_SHOWN = 3
LOW_EVIDENCE_CAVEAT = ("Based on limited data (low evidence level): treat this as a starting point "
                       "and re-check as more months of records are added.")


def _normalise_type(business_type: Any) -> str:
    t = str(business_type or "").strip().lower()
    return t if t in ("retail", "service") else "other"


def _evidence_text(findings: list[dict[str, Any]]) -> str:
    parts = [f["evidence"] for f in findings[:MAX_EVIDENCE_SHOWN]]
    extra = len(findings) - MAX_EVIDENCE_SHOWN
    return " ".join(parts) + (f" (+{extra} more finding(s) of the same kind.)" if extra > 0 else "")


def _build(rule: Rule, hits: list[dict[str, Any]], btype: str, low_evidence: bool) -> dict[str, Any]:
    hits = sorted(hits, key=lambda f: -SEVERITY_RANK[f["severity"]])  # strongest finding first
    top = SEVERITY_RANK[hits[0]["severity"]]
    ids = [f["id"] for f in hits]
    rec = {
        "id": f"REC-{rule.id}",
        "rule_id": rule.id,
        "finding_ids": ids,
        "issue": rule.issue,
        "supporting_metric": hits[0].get("metric") or rule.supporting_metric,
        "evidence": _evidence_text(hits),
        "action": rule.actions.get(btype) or rule.actions["other"],
        "priority": PRIORITY_BY_RANK[top],
        "kpi": rule.kpi,
        "expected_direction": ({"metric": rule.expected_metric, "direction": rule.direction}
                               if rule.direction else None),
        "rationale": (f"Generated by rule {rule.id} because {', '.join(ids)} "
                      f"{'was' if len(ids) == 1 else 'were'} reported (highest severity: {hits[0]['severity']}). "
                      f"The wording is tailored to a {btype} business. This is a suggestion to "
                      "investigate and act on, not a guaranteed result."),
    }
    if low_evidence:
        rec["caveat"] = LOW_EVIDENCE_CAVEAT
    return rec


def build_recommendations(findings: Iterable[dict[str, Any]], business_type: str | None = None,
                          evidence_level: str | None = None) -> list[dict[str, Any]]:
    """Recommendations from the combined findings of all analysis modules.

    ``findings`` are contract finding dicts (id, type, severity, evidence, ...). Malformed
    findings (missing id/type/evidence/severity) are ignored. Returns [] when nothing needs action.
    """
    by_type: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for f in findings or []:
        if (isinstance(f, dict) and f.get("id") and f.get("type") and isinstance(f.get("evidence"), str)
                and SEVERITY_RANK.get(f.get("severity"), 0) > 0):
            by_type[f["type"]].append(f)

    btype, low = _normalise_type(business_type), evidence_level == "low"
    recs = []
    for order, rule in enumerate(RULES):
        hits = [f for t in rule.types for f in by_type.get(t, [])]
        if hits:
            recs.append((order, _build(rule, hits, btype, low)))
    recs.sort(key=lambda x: (PRIORITY_ORDER[x[1]["priority"]], x[0]))
    return [r for _, r in recs]
